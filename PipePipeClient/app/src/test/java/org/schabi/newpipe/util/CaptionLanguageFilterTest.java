package org.schabi.newpipe.util;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNotSame;
import static org.junit.Assert.assertSame;
import static org.junit.Assert.assertTrue;
import static org.junit.Assert.fail;

import java.text.Collator;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

import org.junit.Test;
import org.schabi.newpipe.extractor.MediaFormat;
import org.schabi.newpipe.extractor.stream.DeliveryMethod;
import org.schabi.newpipe.extractor.stream.SubtitlesStream;
import org.schabi.newpipe.util.CaptionLanguageFilter.LanguageEntry;

/**
 * Matching, list behavior, and vocabulary coverage for the
 * caption-language allowlist. Empty selection means all languages.
 */
public class CaptionLanguageFilterTest {

    private static SubtitlesStream stream(final String languageCode) {
        return new SubtitlesStream.Builder()
                .setContent("https://example.invalid/" + languageCode, true)
                .setDeliveryMethod(DeliveryMethod.PROGRESSIVE_HTTP)
                .setMediaFormat(MediaFormat.VTT)
                .setLanguageCode(languageCode)
                .setAutoGenerated(false)
                .build();
    }

    private static Set<String> set(final String... codes) {
        return new HashSet<>(Arrays.asList(codes));
    }

    private static List<String> tags(final List<SubtitlesStream> streams) {
        final List<String> tags = new ArrayList<>(streams.size());
        for (final SubtitlesStream stream : streams) {
            tags.add(stream.getLanguageTag());
        }
        return tags;
    }

    @Test
    public void canonicalPrimaryCodeHandlesVariantsAndAliases() {
        assertEquals("en", CaptionLanguageFilter.canonicalPrimaryCode("en"));
        assertEquals("en", CaptionLanguageFilter.canonicalPrimaryCode("en-US"));
        assertEquals("en", CaptionLanguageFilter.canonicalPrimaryCode("en_US"));
        assertEquals("en", CaptionLanguageFilter.canonicalPrimaryCode("EN"));
        assertEquals("pt", CaptionLanguageFilter.canonicalPrimaryCode("pt-BR"));
        assertEquals("zh", CaptionLanguageFilter.canonicalPrimaryCode("zh-Hant"));
        assertEquals("he", CaptionLanguageFilter.canonicalPrimaryCode("iw"));
        assertEquals("he", CaptionLanguageFilter.canonicalPrimaryCode("he"));
        assertEquals("he", CaptionLanguageFilter.canonicalPrimaryCode("iw-IL"));
        assertEquals("id", CaptionLanguageFilter.canonicalPrimaryCode("in-ID"));
        assertEquals("", CaptionLanguageFilter.canonicalPrimaryCode("und"));
        assertEquals("", CaptionLanguageFilter.canonicalPrimaryCode("UND"));
        assertEquals("", CaptionLanguageFilter.canonicalPrimaryCode(" und "));
        assertEquals("", CaptionLanguageFilter.canonicalPrimaryCode("und-US"));
        assertEquals("he", CaptionLanguageFilter.canonicalPrimaryCode("IW"));
        assertEquals("id", CaptionLanguageFilter.canonicalPrimaryCode("IN"));
        assertEquals("yi", CaptionLanguageFilter.canonicalPrimaryCode("JI"));
        assertEquals("id", CaptionLanguageFilter.canonicalPrimaryCode("in"));
        assertEquals("id", CaptionLanguageFilter.canonicalPrimaryCode("id"));
        assertEquals("yi", CaptionLanguageFilter.canonicalPrimaryCode("ji"));
        assertEquals("yi", CaptionLanguageFilter.canonicalPrimaryCode("yi"));
        assertEquals("", CaptionLanguageFilter.canonicalPrimaryCode(null));
        assertEquals("", CaptionLanguageFilter.canonicalPrimaryCode(""));
        assertEquals("", CaptionLanguageFilter.canonicalPrimaryCode("   "));
        assertEquals("", CaptionLanguageFilter.canonicalPrimaryCode("-US"));
        assertEquals("en", CaptionLanguageFilter.canonicalPrimaryCode(" en-US "));
        assertEquals("en", CaptionLanguageFilter.canonicalPrimaryCode("EN_us"));
    }

    @Test
    public void isTagAllowedCoversEmptySelectionAndMalformedTags() {
        assertTrue(CaptionLanguageFilter.isTagAllowed(
                Collections.emptySet(), "en"));
        assertTrue(CaptionLanguageFilter.isTagAllowed(
                Collections.emptySet(), null));
        assertTrue(CaptionLanguageFilter.isTagAllowed(
                CaptionLanguageFilter.normalizeSelection(null), "und"));
        final Set<String> selected = set("en");
        assertTrue(CaptionLanguageFilter.isTagAllowed(selected, "en-US"));
        assertFalse(CaptionLanguageFilter.isTagAllowed(selected, "de"));
        assertFalse(CaptionLanguageFilter.isTagAllowed(selected, null));
        assertFalse(CaptionLanguageFilter.isTagAllowed(selected, "und"));
        assertFalse(CaptionLanguageFilter.isTagAllowed(selected, ""));
    }

    @Test
    public void primaryCodeOfHandlesNullAndUndetermined() {
        assertEquals("", CaptionLanguageFilter.primaryCodeOf(null));
        assertEquals("", CaptionLanguageFilter.primaryCodeOf(new Locale("und")));
        assertEquals("en", CaptionLanguageFilter.primaryCodeOf(Locale.ENGLISH));
        assertEquals("he", CaptionLanguageFilter.primaryCodeOf(new Locale("iw")));
        assertEquals("en", CaptionLanguageFilter.primaryCodeOf(new Locale("en", "US")));
    }

    @Test
    public void displayNameForFallsBackToUppercaseCode() {
        assertEquals("English",
                CaptionLanguageFilter.displayNameFor("en", Locale.ENGLISH));
        assertEquals("XX",
                CaptionLanguageFilter.displayNameFor("xx", Locale.ENGLISH));
    }

    @Test
    public void sortedDisplayNamesHandlesNullSelection() {
        assertTrue(CaptionLanguageFilter.sortedDisplayNames(null,
                Collections.emptyMap(),
                Collator.getInstance(Locale.ENGLISH)).isEmpty());
    }

    @Test
    public void displayNameFallbackIgnoresDefaultLocale() {
        final Locale previousDefault = Locale.getDefault();
        Locale.setDefault(new Locale("tr"));
        try {
            // "xi" has no display name; Turkish uppercasing of "xi" would be
            // "Xİ", so this pins the Locale.ROOT fallback ("XI").
            assertEquals("XI",
                    CaptionLanguageFilter.displayNameFor("xi", Locale.ENGLISH));
        } finally {
            Locale.setDefault(previousDefault);
        }
    }

    @Test
    public void allowAllPathSkipsNullElements() {
        final List<SubtitlesStream> source =
                new ArrayList<>(Arrays.asList(stream("en"), null));
        assertEquals(Collections.singletonList("en"),
                tags(CaptionLanguageFilter.filterSubtitles(null, source)));
        assertEquals(Collections.singletonList("en"),
                tags(CaptionLanguageFilter.filterSubtitles(
                        set("en"), Arrays.asList(null, stream("en")))));
    }

    @Test
    public void blankOnlySelectionShowsAll() {
        final List<SubtitlesStream> source = Arrays.asList(stream("en"), stream("de"));
        assertEquals(2, CaptionLanguageFilter.filterSubtitles(
                set("", "   "), source).size());
    }

    @Test
    public void emptySelectionReturnsEveryStreamInNewList() {
        final List<SubtitlesStream> source =
                Arrays.asList(stream("en"), stream("pt-BR"));
        final List<List<SubtitlesStream>> results = Arrays.asList(
                CaptionLanguageFilter.filterSubtitles(null, source),
                CaptionLanguageFilter.filterSubtitles(
                        Collections.emptySet(), source));
        for (final List<SubtitlesStream> result : results) {
            assertEquals(Arrays.asList("en", "pt-BR"), tags(result));
            assertNotSame(source, result);
            // Same objects, original order.
            assertSame(source.get(0), result.get(0));
            assertSame(source.get(1), result.get(1));
        }
    }

    @Test
    public void singleLanguageKeepsManualAndRegionalVariants() {
        final List<SubtitlesStream> source = Arrays.asList(
                stream("en"), stream("en-US"), stream("en-GB"), stream("de"));
        final List<SubtitlesStream> result =
                CaptionLanguageFilter.filterSubtitles(set("en"), source);
        assertEquals(Arrays.asList("en", "en-US", "en-GB"), tags(result));
    }

    @Test
    public void multipleLanguagesKeepOriginalOrder() {
        final List<SubtitlesStream> source = Arrays.asList(
                stream("de"), stream("en"), stream("pt-PT"), stream("pt-BR"),
                stream("fr"));
        final List<SubtitlesStream> result =
                CaptionLanguageFilter.filterSubtitles(set("pt", "en"), source);
        assertEquals(Arrays.asList("en", "pt-PT", "pt-BR"), tags(result));
    }

    @Test
    public void aliasesMatchInBothDirections() {
        final List<SubtitlesStream> source = Arrays.asList(stream("iw"), stream("he"));
        assertEquals(2, CaptionLanguageFilter
                .filterSubtitles(set("he"), source).size());
        assertEquals(2, CaptionLanguageFilter
                .filterSubtitles(set("iw"), source).size());
    }

    @Test
    public void undeterminedAndMalformedTagsAreExcluded() {
        final List<SubtitlesStream> source = Arrays.asList(
                stream("en"), stream("de"), stream("und"), stream("123"));
        final List<SubtitlesStream> result =
                CaptionLanguageFilter.filterSubtitles(set("en"), source);
        assertEquals(Collections.singletonList("en"), tags(result));
        // Empty allowlist still shows everything, including undetermined tags.
        assertEquals(4, CaptionLanguageFilter
                .filterSubtitles(Collections.emptySet(), source).size());
    }

    @Test
    public void inputsAreNeverMutated() {
        final List<SubtitlesStream> source = new ArrayList<>(
                Arrays.asList(stream("en"), stream("de")));
        final Set<String> selection = new HashSet<>(Collections.singletonList("en"));
        final List<SubtitlesStream> result =
                CaptionLanguageFilter.filterSubtitles(selection, source);
        result.clear();
        assertEquals(2, source.size());
        assertEquals(set("en"), selection);
    }

    @Test
    public void nullSourceReturnsEmptyList() {
        assertTrue(CaptionLanguageFilter
                .filterSubtitles(set("en"), null).isEmpty());
        assertTrue(CaptionLanguageFilter
                .filterSubtitles(null, null).isEmpty());
    }

    @Test
    public void vocabularyIncludesRequiredThreeLetterCodes() {
        final List<LanguageEntry> vocabulary =
                CaptionLanguageFilter.buildVocabulary(
                        Locale.ENGLISH, Arrays.asList(Locale.getAvailableLocales()));
        final Set<String> codes = new HashSet<>();
        for (final LanguageEntry entry : vocabulary) {
            codes.add(entry.code);
        }
        assertTrue(codes.contains("en"));
        assertTrue(codes.contains("yue"));
        assertTrue(codes.contains("ceb"));
        assertTrue(codes.contains("haw"));
        assertFalse(codes.contains("und"));
        // Every code is a canonical two- or three-letter primary.
        for (final String code : codes) {
            assertEquals(code, CaptionLanguageFilter.canonicalPrimaryCode(code));
            assertTrue(code.length() >= 2 && code.length() <= 3);
        }
    }

    @Test
    public void vocabularyDeduplicatesAliasesAndSorts() {
        final List<LanguageEntry> vocabulary =
                CaptionLanguageFilter.buildVocabulary(Locale.ENGLISH,
                        Arrays.asList(new Locale("iw"), new Locale("he"),
                                Locale.ENGLISH, Locale.FRENCH));
        final List<String> codes = new ArrayList<>();
        for (final LanguageEntry entry : vocabulary) {
            codes.add(entry.code);
        }
        assertEquals(1, Collections.frequency(codes, "he"));
        // Names sorted with the display locale's collator ( extras included).
        final Collator collator = Collator.getInstance(Locale.ENGLISH);
        final List<String> names = new ArrayList<>();
        for (final LanguageEntry entry : vocabulary) {
            names.add(entry.name);
        }
        final List<String> sorted = new ArrayList<>(names);
        Collections.sort(sorted, collator);
        assertEquals(sorted, names);
    }

    @Test
    public void nameMapIsUnmodifiable() {
        final Map<String, String> map = CaptionLanguageFilter.nameMap(
                CaptionLanguageFilter.buildVocabulary(
                        Locale.ENGLISH, Collections.singletonList(Locale.ENGLISH)));
        try {
            map.put("xx", "Xx");
            fail("nameMap should be unmodifiable");
        } catch (final UnsupportedOperationException expected) {
            // Expected: the cached map must reject mutation.
        }
    }

    @Test
    public void summaryNamesAreLocalizedAndSorted() {
        final Map<String, String> codeToName = CaptionLanguageFilter.nameMap(
                CaptionLanguageFilter.buildVocabulary(
                        Locale.ENGLISH,
                        Arrays.asList(Locale.ENGLISH, Locale.GERMAN)));
        final List<String> names = CaptionLanguageFilter.sortedDisplayNames(
                set("de", "en"), codeToName, Collator.getInstance(Locale.ENGLISH));
        assertEquals(Arrays.asList("English", "German"), names);
        // Unknown codes fall back to uppercase instead of disappearing.
        final List<String> fallback = CaptionLanguageFilter.sortedDisplayNames(
                set("xx"), codeToName, Collator.getInstance(Locale.ENGLISH));
        assertEquals(Collections.singletonList("XX"), fallback);
    }

    @Test
    public void normalizeSelectionIsIndependentAndCanonical() {
        final Set<String> stored = new HashSet<>(Arrays.asList("EN-US", "iw", "", null));
        final Set<String> normalized = CaptionLanguageFilter.normalizeSelection(stored);
        assertEquals(set("en", "he"), normalized);
        assertNotSame(stored, normalized);
        assertTrue(CaptionLanguageFilter.normalizeSelection(null).isEmpty());
    }
}
